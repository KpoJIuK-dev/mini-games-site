// Обработка ввода промокода
const promoInput = document.getElementById('promo-input');
const promoBtn = document.querySelector('#promo-btn');
const rewardText = document.querySelector('.modal-success');

promoInput.addEventListener('input', function (e) {
    e.target.value = e.target.value
        .replace(/[^\da-zA-Z]/g, '') // Убираем нецифровые и небуквенные символы
        .replace(/(.{4})/g, '$1 ')  // Разбиваем на группы по 4 символа
        .trim();

    // Активируем или деактивируем кнопку
    if (e.target.value.replace(/\s+/g, '').length === 12) {
        promoBtn?.removeAttribute('disabled');
        promoBtn?.classList.remove('disabled');
    } else {
        promoBtn?.setAttribute('disabled', 'disabled');
        promoBtn?.classList.add('disabled');
    }
});

promoBtn?.addEventListener('click', e => {
    e.preventDefault();

    const loading = document.querySelector('.loading');
    loading.style.display = 'block';

    setTimeout(() => {
        loading.style.display = 'none';
        const inputCode = promoInput.value.replace(/\s+/g, '').toUpperCase(); // Приводим к верхнему регистру

        if (usedPromocodes.includes(inputCode)) {
            showModal('bad', getMessage('error'));
        } else if (promocodes[inputCode]) {
            // Успешная активация
            showModal('good', getMessage('success', promocodes[inputCode]));

            // Сохраняем использованный код
            usedPromocodes.push(inputCode);
            sessionStorage.setItem('usedPromocodes', JSON.stringify(usedPromocodes));
        } else {
            // Код не найден
            showModal('bad', getMessage('error'));
        }

        promoInput.value = '';
    }, 1500);
});

// Функция отображения модальных окон
function showModal(type, message) {
    const modalClass = type === 'good' ? '.modal-good' : '.modal-bad';
    const modal = document.querySelector(modalClass);
    const modalContent = modal?.querySelector('.modal-content');
    const modalMessage = modal?.querySelector(type === 'good' ? '.modal-success' : '.modal-error');

    if (modal && modalContent && modalMessage) {
        modalMessage.innerHTML = message;
        modal.style.display = 'block';
        modalContent.classList.add('modal-in');

        setTimeout(() => modalContent.classList.remove('modal-in'), 400);
    }
}

// Закрытие модальных окон
function closeModal(type) {
    const modalClass = type === 'good' ? '.modal-good' : '.modal-bad';
    const modal = document.querySelector(modalClass);
    const modalContent = modal?.querySelector('.modal-content');

    if (modal && modalContent) {
        modalContent.classList.add('modal-out');
        setTimeout(() => {
            modal.style.display = 'none';
            modalContent.classList.remove('modal-out');
        }, 300);
    }
}

document.querySelector('.btn-good-close')?.addEventListener('click', e => {
    e.preventDefault();
    closeModal('good');
});

document.querySelector('.btn-bad-close')?.addEventListener('click', e => {
    e.preventDefault();
    closeModal('bad');
});
