// Функция получения локализованного текста
function getMessage(type, reward = '') {
    const messageTemplate = messages[currentLang]?.[type] || messages.en[type];
    return messageTemplate.replace('${reward}', reward);
}

// Извлечение имени из URL
function getQueryParam(param) {
    const urlParams = new URLSearchParams(window.location.search);
    return urlParams.get(param);
}

